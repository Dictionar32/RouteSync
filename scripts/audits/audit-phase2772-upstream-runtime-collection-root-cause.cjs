const fs = require('fs');
const path = require('path');
const root = path.resolve(__dirname, '../..');
const read = p => fs.readFileSync(path.join(root, p), 'utf8');
const checks = [];
const check = (name, ok, evidence) => checks.push({ name, ok: Boolean(ok), evidence });
const collections = read('packages/core/src/types/upstream/collections.ts');
const model = read('packages/core/src/types/upstream/highLevelSourceModel.ts');
const ast = read('packages/core/src/types/upstream/ast.ts');
const pipeline = read('packages/core/src/compiler/scanner/wiring/laravelSourceAstPipeline.ts');
const lowerer = read('packages/core/src/compiler/scanner/wiring/routeManifestLowerer.ts');
const projection = read('packages/core/src/compiler/scanner/wiring/routeManifestProjectionInputs.ts');
check('canonical Sequence ADT is defined upstream', /export type Sequence<T>\s*=/.test(collections), 'types/upstream/collections.ts');
check('SourceDiscovery carries readonly-array collection', /kind: 'scanned';\s*readonly items: readonly T\[\]/s.test(collections), 'types/upstream/collections.ts');
check('SourceModelCatalog independently uses Sequence collections', /interface SourceModelCatalog[\s\S]*?readonly controllers: Sequence<ControllerSemanticNode>/m.test(model), 'types/upstream/highLevelSourceModel.ts');
check('array-to-Sequence conversion remains in source-model path', /sequenceAlgebra\.fromArray/.test(model), 'types/upstream/highLevelSourceModel.ts');
check('AST collection aliases retain Sequence', /export type (?:Expressions|SourceStatements|ModelRelations|RouteParameters)\s*=.*Sequence</s.test(collections), 'types/upstream/collections.ts');
