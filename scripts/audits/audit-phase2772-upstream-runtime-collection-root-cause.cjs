check('manifest lowering rejects not-scanned states explicitly', /not_scanned/.test(lowerer), 'compiler/scanner/wiring/routeManifestLowerer.ts');
check('projection inputs reject not-scanned states explicitly', /not_scanned/.test(projection), 'compiler/scanner/wiring/routeManifestProjectionInputs.ts');
const failures = checks.filter(x => !x.ok);
console.log(JSON.stringify({ audit: 'phase2772-upstream-runtime-collection-root-cause', passed: checks.length - failures.length, total: checks.length, checks }, null, 2));
if (failures.length) process.exitCode = 1;
