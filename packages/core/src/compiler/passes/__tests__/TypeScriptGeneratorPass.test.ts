// Batch 3: Pass Configuration Tests (7 tests)
// ============================================================================

describe('TypeScriptGeneratorPass - Configuration', () => {
    let pass: TypeScriptGeneratorPass;

    beforeEach(() => {
        pass = new TypeScriptGeneratorPass();
    });

    it('should have correct pass name', () => {
        expect(pass.name).toBe('TypeScriptGenerator');
    });

    it('should have correct PassDescriptor', () => {
        expect(pass.descriptor.consumes).toEqual(['SemanticTypes']);
        expect(pass.descriptor.produces).toEqual(['GeneratedTypeScript']);
    });

    it('should have correct dependencies', () => {
        expect(pass.requires).toHaveLength(1);
        expect(pass.requires[0].artifact).toBe('SemanticTypes');
        expect(pass.requires[0].producer).toBeUndefined();
    });

    it('should have correct input witnesses', () => {
        expect(pass.inputWitnesses).toHaveLength(1);
        expect(pass.inputWitnesses[0].key).toBe('SemanticTypes');
    });

    it('should have correct output keys', () => {
        expect(pass.outputKeys).toHaveLength(1);
        expect(pass.outputKeys[0]).toBe('GeneratedTypeScript');
    });

    it('should be instantiable without config', () => {
        const defaultPass = new TypeScriptGeneratorPass();
        expect(defaultPass).toBeInstanceOf(TypeScriptGeneratorPass);
    });

    it('should be instantiable with strict config', () => {
        const strictPass = new TypeScriptGeneratorPass({ strict: true });
        expect(strictPass).toBeInstanceOf(TypeScriptGeneratorPass);
    });
});

