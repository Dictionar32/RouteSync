import { describe, it, expect, beforeEach } from 'vitest';
import { TypeScriptGeneratorPass } from '../TypeScriptGeneratorPass';
import type { SemanticTypesArtifact } from '../TypeScriptGeneratorPass';
import { PrimitiveType, PrimitiveKind, ReferenceType, ObjectType } from '../../types/SemanticType';
import { ImmutableMap, ImmutableSet } from '../../utils/ImmutableCollections';
import { CompilationContext } from '../CompilationContext';

// ============================================================================
// Test Utilities & Mock Data Generators
// ============================================================================

/**
 * Create mock PrimitiveType
 */
function createMockPrimitiveType(primitiveKind: PrimitiveKind): PrimitiveType {
    return new PrimitiveType(primitiveKind);
}

/**
 * Create mock ReferenceType
 */
function createMockReferenceType(namespace: string, name: string): ReferenceType {
    return new ReferenceType(namespace, name);
}

/**
 * Create mock ObjectType
 */
function createMockObjectType(
    properties: Map<string, PrimitiveType>
): ObjectType {
    return new ObjectType(
        new ImmutableMap(properties),
        new ImmutableSet(new Set(Array.from(properties.keys()))),
        undefined, // no base object
        [], // no interfaces
        new ImmutableMap(new Map()) // no annotations
    );
}

/**
 * Create mock SemanticTypesArtifact
 */
function createMockSemanticTypesArtifact(
    types: readonly (PrimitiveType | ReferenceType | ObjectType)[]
): SemanticTypesArtifact {
    return {
        typeId: 'SemanticTypes',
        types,
        metadata: {
            hash: 'mock-hash-123',
            producer: 'MockProducer',
            dependencies: [],
            timestamp: Date.now(),
            revision: '1.0.0'
        }
    };
}

