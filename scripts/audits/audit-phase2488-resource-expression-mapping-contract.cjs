const fs = require('node:fs');
const path = require('node:path');
const root = path.resolve(__dirname, '../..');
const read = (relative) => fs.readFileSync(path.join(root, relative), 'utf8');
const checks = [];
const assert = (name, condition) => checks.push({ name, passed: Boolean(condition) });
const contractPath = 'packages/core/src/types/upstream/resourceAstExpressionMappingInterface.ts';
const mapperPath = 'packages/core/src/compiler/scanner/operations/resourceAstExpressionMapper.ts';
const upstreamBarrelPath = 'packages/core/src/types/upstream/index.ts';
const publicEntryPath = 'packages/core/src/index.ts';
const contract = read(contractPath);
const mapper = read(mapperPath);
const resourceAuthority = read('packages/core/src/compiler/frontend/php/routeAst/resourceExpressionSemanticAuthority.ts');
const upstreamBarrel = read(upstreamBarrelPath);
const publicEntry = read(publicEntryPath);
assert('upstream contract exists', fs.existsSync(path.join(root, contractPath)));
assert('contract models syntax and provenance as a named input', /interface ResourceAstExpressionMappingInput<SyntaxValue>\s*\{[\s\S]*readonly value: SyntaxValue;[\s\S]*readonly sourceFile: SourceFile;/s.test(contract));
assert('operation contract accepts the named input', /interface ResourceAstExpressionMappingOperationInterface<SyntaxValue>\s*\{\s*\(input: ResourceAstExpressionMappingInput<SyntaxValue>\): ResourceExpressionModel;/s.test(contract));
assert('upstream contract does not import scanner-owned AST', !/compiler\/scanner|PhpAstValue/.test(contract));
assert('mapper imports the upstream operation contract', mapper.includes("types/upstream/resourceAstExpressionMappingInterface"));
assert('mapper exports a contract-typed const operation', /export const mapResourceAstExpression:\s*ResourceAstExpressionMappingOperationInterface<PhpAstValue>\s*=/.test(mapper));
assert('mapper no longer exposes positional runtime parameters', !/export const resolveAstValueToExpression|export function resolveAstValueToExpression/.test(mapper));
assert('contract is exported by upstream barrel', upstreamBarrel.includes("export * from './resourceAstExpressionMappingInterface'"));
assert('input and operation contract are exported by public core entry', publicEntry.includes('ResourceAstExpressionMappingInput, ResourceAstExpressionMappingOperationInterface') && publicEntry.includes('ResourceAstExpressionMappingAuthorityInterface'));
assert('new contract has no relation/foundation dependency', !/semantic\/(relations|foundation)/.test(contract));
assert('legacy relation dependencies are explicitly detected, not hidden', /semantic\/relations/.test(resourceAuthority) && !/semantic\/relations/.test(mapper));
for (const check of checks) console.log(`${check.passed ? 'PASS' : 'FAIL'} ${check.name}`);
console.log(`\n${checks.filter((check) => check.passed).length}/${checks.length} assertions passed`);
if (checks.some((check) => !check.passed)) process.exitCode = 1;
