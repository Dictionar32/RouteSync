const fs = require('node:fs');
const path = require('node:path');
const root = process.cwd();
const read = (p) => fs.readFileSync(path.join(root, p), 'utf8');
const exists = (p) => fs.existsSync(path.join(root, p));
const checks = [];
const check = (label, ok) => checks.push({ label, passed: Boolean(ok) });
const legacyPath = 'packages/core/src/compiler/scanner/StaticLaravelScanner.ts';
const legacy = read(legacyPath);
const oldTest = read('packages/core/src/compiler/scanner/__test__/StaticLaravelScanner.spec.ts');
const cli = read('packages/cli/src/commands/scan.ts') + read('packages/cli/src/commands/sync.ts');
const builder = read('packages/core/src/compiler/scanner/wiring/upstreamManifestBuilder.ts');
const identity = read('packages/core/src/types/upstream/sourceProjectIdentity.ts');
const dataflow = read('packages/core/src/types/dataflow/dataFlowInterface.ts');
check('legacy StaticLaravelScanner implementation file is intentionally empty', legacy.length === 0);
check('legacy implementation has no production importers', !/StaticLaravelScanner/.test(cli));
check('CLI consumes the canonical manifestBuilder interface', /manifestBuilder\.build\(sourceProject\)/.test(cli));
check('canonical manifest producer validates and builds upstream source model', /validateCompleteSourceAst/.test(builder) && /buildCompleteLaravelSourceModel/.test(builder));
check('source identity is implemented in upstream sourceProjectIdentity module', /export const createLaravelSourceProjectIdentity/.test(identity));
check('data-flow interface remains domain-neutral', !/Laravel|StaticLaravelScanner|Controller|Resource|Schema/.test(dataflow));
check('legacy scanner test now exercises canonical producer, not retired facade', /manifestBuilder\.build\(sourceProject\)/.test(oldTest) && !/StaticLaravelScanner\.scan/.test(oldTest));
check('scanner file is retained in place rather than deleting or renaming it', exists(legacyPath));
const failures = checks.filter((x) => !x.passed);
for (const item of checks) process.stdout.write(`${item.passed ? 'PASS' : 'FAIL'} ${item.label}\n`);
process.stdout.write(`\n${checks.length - failures.length}/${checks.length} checks passed\n`);
if (failures.length) process.exitCode = 1;
