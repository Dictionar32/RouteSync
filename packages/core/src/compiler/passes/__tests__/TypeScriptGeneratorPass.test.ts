// Batch 4: Pass Execution Tests (9 tests)
// ============================================================================

describe('TypeScriptGeneratorPass - Execution', () => {
    let pass: TypeScriptGeneratorPass;

    beforeEach(() => {
        pass = new TypeScriptGeneratorPass();
    });

    it('should process empty types array', () => {
        const input = createMockSemanticTypesArtifact([]);

        const [result] = pass.run([input], CompilationContext.default());

        expect(result.typeId).toBe('GeneratedTypeScript');
        expect(result.code).toContain('// Generated by TypeScriptGenerator');
        expect(result.generationMetadata.typeCount).toBe(0);
    });

    it('should process single primitive type', () => {
        const primitiveType = createMockPrimitiveType(PrimitiveKind.STRING);
        const input = createMockSemanticTypesArtifact([primitiveType]);

        const [result] = pass.run([input], CompilationContext.default());

        expect(result.typeId).toBe('GeneratedTypeScript');
        expect(result.generationMetadata.typeCount).toBe(1);
    });

    it('should process single reference type', () => {
        const refType = createMockReferenceType('App\\Models', 'User');
        const input = createMockSemanticTypesArtifact([refType]);

        const [result] = pass.run([input], CompilationContext.default());

        expect(result.typeId).toBe('GeneratedTypeScript');
        expect(result.generationMetadata.typeCount).toBe(1);
    });

    it('should process single object type', () => {
        const properties = new Map<string, PrimitiveType>();
        properties.set('name', createMockPrimitiveType(PrimitiveKind.STRING));
        properties.set('age', createMockPrimitiveType(PrimitiveKind.NUMBER));

        const objectType = createMockObjectType(properties);
        const input = createMockSemanticTypesArtifact([objectType]);

        const [result] = pass.run([input], CompilationContext.default());

        expect(result.typeId).toBe('GeneratedTypeScript');
        expect(result.generationMetadata.typeCount).toBe(1);
        expect(result.generationMetadata.interfaceCount).toBe(1);
    });

    it('should process multiple types', () => {
        const types = [
            createMockPrimitiveType(PrimitiveKind.STRING),
            createMockPrimitiveType(PrimitiveKind.NUMBER),
            createMockReferenceType('App\\Models', 'User')
        ];
        const input = createMockSemanticTypesArtifact(types);

        const [result] = pass.run([input], CompilationContext.default());

        expect(result.generationMetadata.typeCount).toBe(3);
    });

    it('should generate valid artifact metadata', () => {
        const input = createMockSemanticTypesArtifact([]);

        const [result] = pass.run([input], CompilationContext.default());

        expect(result.metadata.producer).toBe('TypeScriptGenerator');
        expect(result.metadata.dependencies).toContain('SemanticTypes');
        expect(result.metadata.hash).toBeDefined();
        expect(result.metadata.timestamp).toBeGreaterThan(0);
        expect(result.metadata.revision).toBe('1.0.0');
    });

    it('should generate valid generationMetadata', () => {
        const input = createMockSemanticTypesArtifact([]);

        const [result] = pass.run([input], CompilationContext.default());

        expect(result.generationMetadata.generatorVersion).toBe('1.0.0');
        expect(result.generationMetadata.typeCount).toBeGreaterThanOrEqual(0);
        expect(result.generationMetadata.interfaceCount).toBeGreaterThanOrEqual(0);
        expect(result.generationMetadata.importCount).toBeGreaterThanOrEqual(0);
        expect(result.generationMetadata.linesOfCode).toBeGreaterThan(0);
        expect(result.generationMetadata.warnings).toBeInstanceOf(Array);
    });

    it('should generate TypeScript code string', () => {
        const input = createMockSemanticTypesArtifact([]);

        const [result] = pass.run([input], CompilationContext.default());

        expect(typeof result.code).toBe('string');
        expect(result.code.length).toBeGreaterThan(0);
        expect(result.code).toContain('Generated');
    });

    it('should return output in correct tuple format', () => {
        const input = createMockSemanticTypesArtifact([]);

        const output = pass.run(
            [input],
            CompilationContext.default(),
        );

        expect(Array.isArray(output)).toBe(true);
        expect(output).toHaveLength(1);
        expect(output[0].typeId).toBe('GeneratedTypeScript');
    });
});

