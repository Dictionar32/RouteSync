const fs = require('node:fs');
const path = require('node:path');
const root = path.resolve(__dirname, '../..');
const read = (file) => fs.readFileSync(path.join(root, file), 'utf8');
const checks = [];
const assert = (name, condition) => checks.push({ name, passed: Boolean(condition) });
const contractPath = 'packages/core/src/types/upstream/resourceDefinitionBindingInterface.ts';
const binderPath = 'packages/core/src/compiler/scanner/binders/resource/resourceBinder.ts';
const upstreamBarrelPath = 'packages/core/src/types/upstream/index.ts';
const publicIndexPath = 'packages/core/src/index.ts';
const docsPath = 'docs/PHASE2484-RESOURCE-BINDING-OPERATION-CONTRACT.md';
const knowledgeContractPath = 'packages/core/src/types/upstream/resourceModelKnowledgeDataFlowInterface.ts';
const knowledgeImplementationPath = 'packages/core/src/compiler/semantic/resourceModelKnowledgeDataFlowAuthority.ts';
const contract = read(contractPath);
const binder = read(binderPath);
const upstreamBarrel = read(upstreamBarrelPath);
const publicIndex = read(publicIndexPath);
const docs = read(docsPath);
const knowledgeContract = read(knowledgeContractPath);
const knowledgeImplementation = read(knowledgeImplementationPath);
assert('upstream Resource binding input contract exists', /interface ResourceDefinitionBindingInput</u.test(contract));
assert('upstream Resource binding operation contract exists', /interface ResourceDefinitionBindingOperationInterface/u.test(contract));
assert('binder export is interface-typed const', /export const bindResourceDefinition:\s*ResourceDefinitionBindingOperation\s*=/u.test(binder));
assert('binder no longer exports function declarations', !/export function\s+(?:bindResourceDefinition|requireVariableTargetName|requireStringArrayKey)\b/u.test(binder));
assert('binder consumes upstream operation contract', /types\/upstream\/resourceDefinitionBindingInterface/u.test(binder));
assert('upstream barrel exports binding contract', /export \* from '\.\/resourceDefinitionBindingInterface';/u.test(upstreamBarrel));
assert('Resource knowledge payload has an upstream-owned contract', /interface ResourceModelKnowledgeDataFlow/u.test(knowledgeContract));
assert('knowledge operations are owned by compiler semantic authority', /resourceModelKnowledgeDataFlowOperations:\s*ResourceModelKnowledgeDataFlowOperationsInterface/u.test(knowledgeImplementation));
assert('binder no longer imports its knowledge payload from subscanners', !/import\(["']\.\.\/subscanners\//u.test(binder));
assert('public core index exports binding contract', /resourceDefinitionBindingInterface/u.test(publicIndex));
assert('remaining relation/subscanner ownership is explicitly documented', /still imports `semantic\/relations` and the legacy `subscanners\/resourceProducer`/u.test(docs));
assert('phase does not falsely claim scanner retirement', /does \*\*not\*\* complete Laravel scanner retirement/u.test(docs));
for (const check of checks) console.log(`${check.passed ? 'PASS' : 'FAIL'} ${check.name}`);
console.log(`\nResult: ${checks.filter((check) => check.passed).length}/${checks.length} assertions passed`);
if (checks.some((check) => !check.passed)) process.exitCode = 1;
