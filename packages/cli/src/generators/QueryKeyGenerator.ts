import {
  RouteManifest,
  CrudResourceGroupDescriptor,
  SingletonResourceGroupDescriptor,
  CustomResourceGroupDescriptor
} from '@routesync/core'
import path from 'path'
import { classifyDomainGraph, ClassifiedDomainGraph, ClassifiedRoute } from './route-classifier'
import { CodeWriter } from './code-writer'

function lowerActionKeyLine(keyName: string, route: ClassifiedRoute): string {
  if (route.hasParams) {
    return `    ${route.actionName}: (params?: string | number | Record<string, unknown>) => [Entity.${keyName}, "${route.actionName}", params ?? {}] as const,`
  }
  return `    ${route.actionName}: () => [Entity.${keyName}, "${route.actionName}"] as const,`
}

function* lowerCrudQueryKeyBlock(
  group: CrudResourceGroupDescriptor<ClassifiedRoute>
): Iterable<string> {
  yield `  ${group.groupName}: {`
  yield `    ...createBaseQueryKey<typeof Entity.${group.keyName}, ${group.primaryKeyType}>(Entity.${group.keyName}),`
  for (const route of group.all) {
    yield lowerActionKeyLine(group.keyName, route)
  }
  yield `  },`
}

function* lowerNonCrudQueryKeyBlock(
  group: SingletonResourceGroupDescriptor<ClassifiedRoute> | CustomResourceGroupDescriptor<ClassifiedRoute>
): Iterable<string> {
  yield `  ${group.groupName}: {`
  yield `    all: () => [Entity.${group.keyName}] as const,`
  for (const route of group.all) {
    yield lowerActionKeyLine(group.keyName, route)
  }
  yield `  },`
}

/**
 * Pure generator lowering the entire query-key.ts source file.
 * Streams lines without creating nested staging arrays.
 */
export function* lowerQueryKeySource(
  graph: ClassifiedDomainGraph<ClassifiedRoute>
): Iterable<string> {
  yield `// Auto-generated by routesync. Do not edit manually.`
  yield ``

  // ── 1. Entity constants ───────────────────────────────────────────────
  yield `/* =========================`
  yield `   ENTITY CONSTANTS`
  yield `========================= */`
  yield `export const Entity = {`
  for (const group of graph.resourceGroupGraph.all) {
    yield `  ${group.keyName}: "${group.groupName}",`
  }
  yield `} as const`
  yield ``
  yield `type EntityValue = (typeof Entity)[keyof typeof Entity]`
  yield ``

  // ── 2. Base factory ───────────────────────────────────────────────────
  yield `/* =========================`
  yield `   BASE FACTORY (GENERIC)`
  yield `========================= */`
  yield `const createBaseQueryKey = <T extends EntityValue, TId = string | number, TFilter = Record<string, unknown>>(entity: T) => ({`
  yield `  all:     ()                         => [entity] as const,`
  yield `  lists:   ()                         => [entity, "list"] as const,`
  yield `  list:    (filters?: TFilter)        =>`
  yield `             [entity, "list", filters ?? {}] as const,`
  yield `  details: ()                         => [entity, "detail"] as const,`
  yield `  detail:  (id: TId)                  => [entity, "detail", id] as const,`
  yield `})`
  yield ``

  // ── 3. Query key registry ─────────────────────────────────────────────
  yield `/* =========================`
  yield `   QUERY KEY REGISTRY`
  yield `========================= */`
  yield `export const QueryKey = {`

  for (const group of graph.resourceGroupGraph.all) {
    yield `  /* ===== ${group.titleName.toUpperCase()} ===== */`
    if (group.isCrud) {
      yield* lowerCrudQueryKeyBlock(group)
    } else {
      yield* lowerNonCrudQueryKeyBlock(group)
    }
    yield ``
  }

  yield `} as const`
  yield ``

  // ── 4. Backward-compat exports ────────────────────────────────────────
  yield `/* =========================`
  yield `   BACKWARD COMPATIBLE EXPORTS`
  yield `========================= */`
  for (const group of graph.resourceGroupGraph.all) {
    yield `export const ${group.groupName}Keys = QueryKey.${group.groupName}`
  }
  yield ``
}

export class QueryKeyGenerator {
  static async generate(
    manifest: RouteManifest,
    outputDir: string,
    domainGraph?: ClassifiedDomainGraph<ClassifiedRoute>
  ): Promise<void> {
    const graph = domainGraph ?? classifyDomainGraph(manifest)
    const writer = new CodeWriter()
    writer.write(lowerQueryKeySource(graph))
    await writer.writeToFile(path.join(outputDir, 'query-key.ts'))
  }
}
