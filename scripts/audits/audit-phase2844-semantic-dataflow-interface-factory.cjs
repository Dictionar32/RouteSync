const fs = require('node:fs');
const path = require('node:path');
const root = process.cwd();
const read = (name) => fs.readFileSync(path.join(root, name), 'utf8');
const checks = [];
const check = (label, condition) => checks.push({ label, pass: Boolean(condition) });
const model = read('packages/core/src/types/upstream/semanticDataflow.ts');
const surface = read('packages/core/src/types/upstream/semanticDataflowInterface.ts');
const barrel = read('packages/core/src/index.ts');
const collections = fs.statSync(path.join(root, 'packages/core/src/types/upstream/collections.ts')).size;
const pkg = JSON.parse(read('package.json'));
check('interface factory contract is explicit', /interface SemanticDataflowInterfaceFactoryInterface/.test(model));
check('runtime export is interface-first', /export const semanticDataflowInterfaceFactory:\s*SemanticDataflowInterfaceFactoryInterface\s*=\s*Object\.freeze/.test(model));
check('judgment conversion is a domain operation on the factory', /readonly fromJudgment:\s*\(judgment: SemanticDataflowJudgment\) => SemanticDataflowInterface/.test(model) && /fromJudgment:\s*\(judgment: SemanticDataflowJudgment\): SemanticDataflowInterface/.test(model));
check('legacy exported free conversion function is absent', !/export const semanticDataflowInterfaceFromJudgment\s*=/.test(model) && !/export function semanticDataflowInterfaceFromJudgment/.test(model));
check('conversion preserves authoritative judgment and proof contract', /judgment,\s*reasoning:\s*judgment\.reasoningContract,\s*closed: true/.test(model));
check('upstream interface surface exports the operation', /semanticDataflowInterfaceFactory/.test(surface));
check('core barrel exports the operation value', /export \{[^}]*semanticDataflowInterfaceFactory[^}]*\} from '\.\/types\/upstream\/semanticDataflow'/.test(barrel));
check('core barrel exports the operation interface', /SemanticDataflowInterfaceFactoryInterface/.test(barrel));
check('upstream collections remains empty', collections === 0);
check('audit is registered in package scripts', Object.values(pkg.scripts || {}).includes('node scripts/audits/audit-phase2844-semantic-dataflow-interface-factory.cjs'));
for (const item of checks) console.log(`${item.pass ? 'PASS' : 'FAIL'} ${item.label}`);
console.log(`Phase 2844 semantic dataflow interface factory audit: ${checks.filter(x => x.pass).length}/${checks.length}`);
if (checks.some(x => !x.pass)) process.exitCode = 1;
