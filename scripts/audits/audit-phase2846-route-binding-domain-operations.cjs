const fs = require('node:fs');
const path = require('node:path');
const root = process.cwd();
const read = p => fs.readFileSync(path.join(root, p), 'utf8');
const checks = [];
const test = (name, condition) => { checks.push({ name, passed: Boolean(condition) }); };
const binding = read('packages/core/src/types/upstream/routeBinding.ts');
const requestProjection = read('packages/core/src/types/upstream/semanticDataflowRequestProjection.ts');
const routeProjection = read('packages/core/src/types/upstream/semanticDataflowRouteProjection.ts');
const barrel = read('packages/core/src/index.ts');
test('route binding exports typed factory interface', /interface RouteBindingInterfaceFactoryInterface/.test(binding));
test('route binding factory export is interface-first', /export const routeBindingInterfaceFactory:\s*RouteBindingInterfaceFactoryInterface/.test(binding));
test('legacy exported constructor is removed', !/export const routeBindingInterfaceFrom\s*=/.test(binding));
test('route binding ADT exposes domain operations', /readonly operations: RouteBindingDomainOperationsInterface/.test(binding));
test('domain operations include parameter membership', /readonly containsParameter:/.test(binding));
test('domain operations include bound-state query', /readonly isBound:/.test(binding));
test('membership query is backed by canonical parameter names', /all\.some\(parameter => nameMatches\(parameter\.name, name\)\)/.test(binding));
test('bound query derives from computed bound parameters', /bound\.some\(parameter => nameMatches\(parameter\.name, name\)\)/.test(binding));
test('request projection uses factory operation', /routeBindingInterfaceFactory\.fromParameters/.test(requestProjection));
test('route projection uses factory operation', /routeBindingInterfaceFactory\.fromParameters/.test(routeProjection));
test('public barrel exports factory and operation contracts', /routeBindingInterfaceFactory/.test(barrel) && /RouteBindingDomainOperationsInterface/.test(barrel));
test('upstream collections file remains empty', fs.statSync(path.join(root, 'packages/core/src/types/upstream/collections.ts')).size === 0);
for (const item of checks) console.log(`${item.passed ? 'PASS' : 'FAIL'} ${item.name}`);
console.log(`${checks.filter(x => x.passed).length}/${checks.length} passed`);
if (checks.some(x => !x.passed)) process.exitCode = 1;
