// Batch 5: Error Handling & Edge Cases (7 tests)
// ============================================================================

describe('TypeScriptGeneratorPass - Error Handling', () => {
    let pass: TypeScriptGeneratorPass;

    beforeEach(() => {
        pass = new TypeScriptGeneratorPass();
    });

    it('should handle empty properties in ObjectType', () => {
        const emptyObjectType = createMockObjectType(new Map());
        const input = createMockSemanticTypesArtifact([emptyObjectType]);

        expect(() => pass.run([input], CompilationContext.default())).not.toThrow();

        const [result] = pass.run([input], CompilationContext.default());

        expect(result.generationMetadata.interfaceCount).toBe(1);
    });

    it('should collect warnings for generation errors', () => {
        // Mock type yang complex untuk potential warnings
        const properties = new Map<string, PrimitiveType>();
        properties.set('field1', createMockPrimitiveType(PrimitiveKind.STRING));
        const objectType = createMockObjectType(properties);
        const input = createMockSemanticTypesArtifact([objectType]);

        const [result] = pass.run([input], CompilationContext.default());

        expect(result.generationMetadata.warnings).toBeInstanceOf(Array);
    });

    it('should handle large number of types', () => {
        const largeTypeArray = Array.from({ length: 100 }, (_, i) =>
            createMockPrimitiveType(PrimitiveKind.STRING)
        );
        const input = createMockSemanticTypesArtifact(largeTypeArray);

        expect(() => pass.run([input], CompilationContext.default())).not.toThrow();

        const [result] = pass.run([input], CompilationContext.default());

        expect(result.generationMetadata.typeCount).toBe(100);
    });

    it('should generate empty imports array when no external references', () => {
        const primitiveType = createMockPrimitiveType(PrimitiveKind.STRING);
        const input = createMockSemanticTypesArtifact([primitiveType]);

        const [result] = pass.run([input], CompilationContext.default());

        expect(result.imports).toBeInstanceOf(Array);
        expect(result.imports.length).toBeGreaterThanOrEqual(0);
    });

    it('should generate empty interfaces array when no object types', () => {
        const primitiveType = createMockPrimitiveType(PrimitiveKind.STRING);
        const input = createMockSemanticTypesArtifact([primitiveType]);

        const [result] = pass.run([input], CompilationContext.default());

        expect(result.interfaces).toBeInstanceOf(Array);
    });

    it('should maintain immutability of generated artifact', () => {
        const input = createMockSemanticTypesArtifact([]);

        const [result] = pass.run([input], CompilationContext.default());

        // Try to mutate (should not affect internal state)
        const originalCode = result.code;
        const originalTypeCount = result.generationMetadata.typeCount;

        // Run again with same input

        const [result2] = pass.run([input], CompilationContext.default());

        expect(result2.code).toBe(originalCode);
        expect(result2.generationMetadata.typeCount).toBe(originalTypeCount);
    });

    it('should generate unique hashes for different inputs', () => {
        const input1 = createMockSemanticTypesArtifact([
            createMockPrimitiveType(PrimitiveKind.STRING)
        ]);
        const input2 = createMockSemanticTypesArtifact([
            createMockPrimitiveType(PrimitiveKind.NUMBER)
        ]);

        const [result1] = pass.run([input1], CompilationContext.default());

        const [result2] = pass.run([input2], CompilationContext.default());

        // Hashes might be same or different depending on implementation
        // but both should be valid strings
        expect(typeof result1.metadata.hash).toBe('string');
        expect(typeof result2.metadata.hash).toBe('string');
        expect(result1.metadata.hash.length).toBeGreaterThan(0);
        expect(result2.metadata.hash.length).toBeGreaterThan(0);
    });
});

