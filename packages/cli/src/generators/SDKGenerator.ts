import { RouteManifest, ParsedRoute } from '@routesync/core'
import path from 'path'
import fs from 'fs-extra'

export class SDKGenerator {
  static async generate(manifest: RouteManifest, outputDir: string): Promise<void> {
    const grouped = SDKGenerator.groupByResource(manifest.routes)
    const lines: string[] = []

    lines.push(`// Auto-generated by routesync. Do not edit manually.`)
    lines.push(`// Generated at: ${manifest.generatedAt}`)
    lines.push(``)
    lines.push(`import { defineApi } from '@routesync/sdk'`)
    lines.push(``)
    lines.push(`export const api = defineApi({`)

    for (const [group, routes] of Object.entries(grouped)) {
      lines.push(`  ${group}: {`)

      for (const route of routes) {
        const actionName = SDKGenerator.toActionName(route)
        lines.push(`    ${actionName}: {`)
        lines.push(`      method: '${route.method}',`)
        lines.push(`      path: '${route.path}',`)
        if (route.auth) lines.push(`      auth: true,`)
        lines.push(`    },`)
      }

      lines.push(`  },`)
    }

    lines.push(`})`)
    lines.push(``)
    lines.push(`export default api`)

    await fs.writeFile(path.join(outputDir, 'api.ts'), lines.join('\n'))
  }

  private static groupByResource(routes: ParsedRoute[]): Record<string, ParsedRoute[]> {
    const groups: Record<string, ParsedRoute[]> = {}

    for (const route of routes) {
      const parts = route.path.replace(/^\//, '').split('/')
      const group = parts[0]?.replace(/-/g, '_') ?? 'root'

      if (!groups[group]) groups[group] = []
      groups[group].push(route)
    }

    return groups
  }

  private static toActionName(route: ParsedRoute): string {
    const parts = route.path.replace(/^\//, '').split('/')
    const method = route.method.toLowerCase()

    const hasId = parts.some((p) => p.startsWith('{'))

    if (method === 'get' && !hasId) return 'index'
    if (method === 'get' && hasId) return 'show'
    if (method === 'post') return 'store'
    if (method === 'put' || method === 'patch') return 'update'
    if (method === 'delete') return 'destroy'

    return `${method}Action`
  }
}
